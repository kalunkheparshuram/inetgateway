def draw_pie(cv, c, pal, font, slices, title):
    cv.delete("all")
    cv.configure(bg=c["panel"])
    w, h = max(cv.winfo_width(), 240), max(cv.winfo_height(), 140)
    cv.create_text(8, 8, anchor="nw", text=title, fill=c["fg"], font=font)
    total = sum(v for _, v in slices)
    if total <= 0:
        cv.create_text(w / 2, h / 2, text="No data yet", fill=c["fg"], font=font)
        return
    d = max(60, min(h - 44, int(w * 0.38)))
    x0, y0 = 12, 32 + max(0, (h - 44 - d) // 2)
    box = (x0, y0, x0 + d, y0 + d)
    cum = 0.0
    for i, (label, v) in enumerate(slices):
        colour = pal[i % len(pal)]
        frac = v / total
        if frac >= 0.9999:
            cv.create_oval(*box, fill=colour, outline=c["panel"], width=2)
        else:
            cv.create_arc(*box, start=90 - cum * 360, extent=-frac * 360, fill=colour, outline=c["panel"],
                          width=2, style="pieslice")
        cum += frac
        ly = 36 + i * 19
        cv.create_rectangle(x0 + d + 14, ly, x0 + d + 26, ly + 12, fill=colour, outline=c["fg"])
        text = "%s  %.1f%%" % (label if len(label) <= 20 else label[:19] + "...", frac * 100)
        cv.create_text(x0 + d + 32, ly + 6, anchor="w", text=text, fill=c["fg"], font=font)


