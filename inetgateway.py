TCP_FLAGS = ((0x02, "SYN"), (0x10, "ACK"), (0x01, "FIN"), (0x04, "RST"),
             (0x08, "PSH"), (0x20, "URG"), (0x40, "ECE"), (0x80, "CWR"))
IP_PROTOS = {1: "ICMP", 2: "IGMP", 6: "TCP", 17: "UDP", 58: "ICMPv6"}
ICMP_TYPES = {0: "Echo reply", 3: "Destination unreachable", 5: "Redirect",
              8: "Echo request", 11: "Time exceeded"}
ICMP6_TYPES = {1: "Destination unreachable", 2: "Packet too big", 3: "Time exceeded",
               128: "Echo request", 129: "Echo reply", 133: "Router solicitation",
               134: "Router advertisement", 135: "Neighbor solicitation",
               136: "Neighbor advertisement"}
DNS_TYPES = {1: "A", 2: "NS", 5: "CNAME", 6: "SOA", 12: "PTR", 15: "MX", 16: "TXT",
             28: "AAAA", 33: "SRV", 65: "HTTPS", 255: "ANY"}


def safe_text(b, limit: int = 255) -> str:
    """Captured strings are untrusted: keep printable ASCII only."""
    s = b.decode("latin-1") if isinstance(b, (bytes, bytearray)) else str(b)
    return "".join(ch if 32 <= ord(ch) < 127 else "." for ch in s)[:limit]


def _mac(b: bytes) -> str:
    return ":".join("%02x" % x for x in b)


class Decoded:
    def __init__(self, detail: bool = False):
        self.proto = "?"
        self.src = ""
        self.dst = ""
        self.sport = None
        self.dport = None
        self.info = ""
        self.ipver = 0
        self.l4 = None  # "tcp" / "udp" / None
        self.tcp_flags = 0
        self.dns = None  # "q" / "r" / None
        self.dns_answers = []  # [(queried name, ip)]
        self.detail = detail
        self.layers = []

    def add(self, title, lines):
        if self.detail:
            self.layers.append((title, lines))


def decode(data: bytes, linktype: int, detail: bool = False) -> Decoded:
    d = Decoded(detail)
    try:
        _decode(d, data, linktype)
    except (struct.error, IndexError, ValueError, OverflowError):
        if d.proto in ("?", ""):
            d.proto = "Malformed"
        d.info = "Malformed packet"
    return d


def _decode(d: Decoded, data: bytes, lt: int):
    off = 0
    ethertype = None
    if lt == LINK_ETHERNET:
        d.proto = "Ethernet"
        if len(data) < 14:
            d.info = "Truncated Ethernet frame"
            return
        et = struct.unpack_from("!H", data, 12)[0]
        d.src, d.dst = _mac(data[6:12]), _mac(data[0:6])
        off = 14
        if d.detail:
            d.add("Ethernet II", ["Destination: " + d.dst, "Source: " + d.src, "EtherType: 0x%04x" % et])
        while et in (0x8100, 0x88A8) and len(data) >= off + 4:
            tci, et = struct.unpack_from("!HH", data, off)
            if d.detail:
                d.add("802.1Q VLAN", ["VLAN ID: %d" % (tci & 0x0FFF), "Priority: %d" % (tci >> 13)])
            off += 4
        ethertype = et
    elif lt == LINK_NULL:
        d.proto = "Loopback"
        if len(data) < 4:
            d.info = "Truncated loopback frame"
            return
        fam = struct.unpack_from("<I", data, 0)[0]
        off = 4
        ethertype = 0x0800 if fam == 2 else 0x86DD if fam in (23, 24, 28, 30) else None
    elif lt == LINK_RAW:
        ver = (data[0] >> 4) if data else 0
        ethertype = 0x0800 if ver == 4 else 0x86DD if ver == 6 else None
        d.proto = "IP"
    else:
        d.proto = "Link %d" % lt
        d.info = "Unsupported link type"
        return

    if ethertype == 0x0800:
        _ipv4(d, data, off)
    elif ethertype == 0x86DD:
        _ipv6(d, data, off)
    elif ethertype == 0x0806:
        _arp(d, data, off)
    elif ethertype is None:
        d.info = "Unrecognised network layer"
    else:
        d.info = "EtherType 0x%04x" % ethertype


def _ipv4(d: Decoded, data: bytes, off: int):
    d.proto = "IPv4"
    d.ipver = 4
    if len(data) < off + 20:
        d.info = "Truncated IPv4 header"
        return
    vihl, tos, tlen, ident, ff, ttl, proto, csum = struct.unpack_from("!BBHHHBBH", data, off)
    d.src = socket.inet_ntoa(data[off + 12:off + 16])
    d.dst = socket.inet_ntoa(data[off + 16:off + 20])
    ihl = (vihl & 0x0F) * 4
    if (vihl >> 4) != 4 or ihl < 20:
        d.info = "Bad IPv4 header"
        return
    frag_off = (ff & 0x1FFF) * 8
    payload_off = off + ihl
    # tlen == 0 happens with offload on captured outbound packets: fall back to captured size
    plen = tlen - ihl if tlen >= ihl else max(0, len(data) - payload_off)
    if d.detail:
        d.add("Internet Protocol Version 4", [
            "Header length: %d bytes" % ihl, "Total length: %d" % tlen,
            "Identification: 0x%04x" % ident,
            "Flags: %s%s" % ("DF " if ff & 0x4000 else "", "MF" if ff & 0x2000 else ""),
            "Fragment offset: %d" % frag_off, "TTL: %d" % ttl,
            "Protocol: %d (%s)" % (proto, IP_PROTOS.get(proto, "other")),
            "Source: " + d.src, "Destination: " + d.dst])
    if frag_off:
        d.info = "Fragmented IP (proto %d, offset %d)" % (proto, frag_off)
        return
    _l4(d, data, payload_off, proto, plen)


def _ipv6(d: Decoded, data: bytes, off: int):
    d.proto = "IPv6"
    d.ipver = 6
    if len(data) < off + 40:
        d.info = "Truncated IPv6 header"
        return
    vtf, plen, nh, hlim = struct.unpack_from("!IHBB", data, off)
    d.src = str(ipaddress.IPv6Address(bytes(data[off + 8:off + 24])))
    d.dst = str(ipaddress.IPv6Address(bytes(data[off + 24:off + 40])))
    if d.detail:
        d.add("Internet Protocol Version 6", ["Payload length: %d" % plen, "Next header: %d" % nh,
                                              "Hop limit: %d" % hlim, "Source: " + d.src,
                                              "Destination: " + d.dst])
    pos = off + 40
    remaining = plen if plen else max(0, len(data) - pos)
    for _ in range(8):  # skip hop-by-hop / routing / destination-options headers
        if nh not in (0, 43, 60):
            break
        if len(data) < pos + 2:
            d.info = "Truncated IPv6 extension header"
            return
        nxt, hl = data[pos], (data[pos + 1] + 1) * 8
        pos += hl
        remaining -= hl
        nh = nxt
    if nh == 44:
        d.info = "Fragmented IPv6"
        return
    _l4(d, data, pos, nh, remaining)


def _arp(d: Decoded, data: bytes, off: int):
    d.proto = "ARP"
    if len(data) < off + 28:
        d.info = "Truncated ARP"
        return
    htype, ptype, hlen, plen, op, sha, spa, tha, tpa = struct.unpack_from("!HHBBH6s4s6s4s", data, off)
    sip, tip = socket.inet_ntoa(spa), socket.inet_ntoa(tpa)
    if op == 1:
        d.info = "Who has %s? Tell %s" % (tip, sip)
    elif op == 2:
        d.info = "%s is at %s" % (sip, _mac(sha))
    else:
        d.info = "ARP opcode %d" % op
    if d.detail:
        d.add("Address Resolution Protocol", ["Opcode: %d" % op, "Sender MAC: " + _mac(sha), "Sender IP: " + sip,
                                              "Target MAC: " + _mac(tha), "Target IP: " + tip])


def _l4(d: Decoded, data: bytes, off: int, proto: int, plen: int):
    if proto == 6:
        d.proto, d.l4 = "TCP", "tcp"
        if len(data) < off + 20:
            d.info = "Truncated TCP header"
            return
        sport, dport, seq, ack, offres, flags, win, csum, urg = struct.unpack_from("!HHIIBBHHH", data, off)
        doff = (offres >> 4) * 4
        d.sport, d.dport = sport, dport
        d.tcp_flags = flags
        names = ",".join(n for bit, n in TCP_FLAGS if flags & bit)
        length = max(0, plen - doff)
        d.info = "%d -> %d [%s] Seq=%d Ack=%d Win=%d Len=%d" % (sport, dport, names, seq, ack, win, length)
        if d.detail:
            d.add("Transmission Control Protocol", ["Source port: %d" % sport, "Destination port: %d" % dport,
                                                    "Sequence: %d" % seq, "Acknowledgment: %d" % ack,
                                                    "Header length: %d bytes" % doff, "Flags: " + (names or "none"),
                                                    "Window: %d" % win, "Payload length: %d bytes" % length])
    elif proto == 17:
        d.proto, d.l4 = "UDP", "udp"
        if len(data) < off + 8:
            d.info = "Truncated UDP header"
            return
        sport, dport, ulen, csum = struct.unpack_from("!HHHH", data, off)
        d.sport, d.dport = sport, dport
        d.info = "%d -> %d Len=%d" % (sport, dport, max(0, ulen - 8))
        if d.detail:
            d.add("User Datagram Protocol", ["Source port: %d" % sport, "Destination port: %d" % dport,
                                             "Length: %d" % ulen])
        if 53 in (sport, dport) or 5353 in (sport, dport):
            _dns(d, data, off + 8, "MDNS" if 5353 in (sport, dport) else "DNS")
    elif proto == 1:
        d.proto = "ICMP"
        t, c = struct.unpack_from("!BB", data, off)
        d.info = "%s (type %d, code %d)" % (ICMP_TYPES.get(t, "ICMP"), t, c)
    elif proto == 58:
        d.proto = "ICMPv6"
        t, c = struct.unpack_from("!BB", data, off)
        d.info = "%s (type %d, code %d)" % (ICMP6_TYPES.get(t, "ICMPv6"), t, c)
    elif proto == 2:
        d.proto = "IGMP"
        d.info = "IGMP"
    else:
        d.proto = "IP proto %d" % proto
        d.info = "Protocol %d" % proto


def _dns_name(data: bytes, off: int):
    labels, jumps, pos, end = [], 0, off, None
    while True:
        if pos >= len(data):
            raise ValueError("truncated name")
        ln = data[pos]
        if ln == 0:
            pos += 1
            break
        if ln & 0xC0 == 0xC0:
            if pos + 1 >= len(data):
                raise ValueError("truncated pointer")
            if end is None:
                end = pos + 2
            jumps += 1
            if jumps > 10:
                raise ValueError("pointer loop")
            pos = ((ln & 0x3F) << 8) | data[pos + 1]
            continue
        if ln & 0xC0:
            raise ValueError("reserved label type")
        if pos + 1 + ln > len(data):
            raise ValueError("truncated label")
        labels.append(safe_text(data[pos + 1:pos + 1 + ln], 63))
        pos += 1 + ln
        if sum(len(x) + 1 for x in labels) > 255:
            raise ValueError("name too long")
    return ".".join(labels), (end if end is not None else pos)


def _dns(d: Decoded, data: bytes, off: int, label: str):
    try:
        msg = bytes(data[off:])  # compression pointers are relative to the DNS message start
        if len(msg) < 12:
            return
        ident, flags, qd, an, ns, ar = struct.unpack_from("!HHHHHH", msg, 0)
        if qd < 1:
            return
        name, pos = _dns_name(msg, 12)
        qtype = struct.unpack_from("!H", msg, pos)[0]
        t = DNS_TYPES.get(qtype, "type %d" % qtype)
        resp = bool(flags & 0x8000)
        d.proto = label
        d.dns = "r" if resp else "q"
        if resp and (flags & 0xF) == 0 and an and qd <= 4:
            try:  # collect A/AAAA answers so IPs can be shown with the name the app asked for
                p2 = pos + 4
                for _ in range(qd - 1):
                    _, p2 = _dns_name(msg, p2)
                    p2 += 4
                for _ in range(min(an, 16)):
                    _, p2 = _dns_name(msg, p2)
                    rtype, rclass, ttl, rdlen = struct.unpack_from("!HHIH", msg, p2)
                    p2 += 10
                    rdata = msg[p2:p2 + rdlen]
                    if len(rdata) < rdlen:
                        break
                    p2 += rdlen
                    if rclass == 1 and rtype == 1 and rdlen == 4:
                        d.dns_answers.append((name, socket.inet_ntoa(rdata)))
                    elif rclass == 1 and rtype == 28 and rdlen == 16:
                        d.dns_answers.append((name, str(ipaddress.IPv6Address(rdata))))
            except (struct.error, ValueError):
                pass
        if resp:
            d.info = "Response 0x%04x %s %s (%d answers, rcode %d)" % (ident, t, name, an, flags & 0xF)
            if d.dns_answers:
                d.info += " -> " + ", ".join(ip for _, ip in d.dns_answers[:4])
        else:
            d.info = "Query 0x%04x %s %s" % (ident, t, name)
        if d.detail:
            d.add("Domain Name System", ["Transaction ID: 0x%04x" % ident, "Response: %s" % ("yes" if resp else "no"),
                                         "Questions: %d" % qd, "Answers: %d" % an, "Name: " + name,
                                         "Type: " + t] + ["Answer: %s -> %s" % a for a in d.dns_answers[:8]])
    except (struct.error, ValueError):
        pass  # not DNS after all; keep the plain UDP summary


def hexdump(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        c = data[i:i + 16]
        hx = " ".join("%02x" % b for b in c[:8]) + "  " + " ".join("%02x" % b for b in c[8:])
        rows.append("%04x  %-49s %s" % (i, hx, "".join(chr(b) if 32 <= b < 127 else "." for b in c)))
    return "\n".join(rows)


