class TableRefresher(threading.Thread):
    def __init__(self, attributor: Attributor):
        super().__init__(daemon=True)
        self.attributor = attributor
        self.stop_evt = threading.Event()

    def run(self):
        cycle = 0
        while not self.stop_evt.is_set():
            try:
                self.attributor.update(*read_connection_tables())
                self.attributor.error = ""
            except Exception as e:  # keep capturing; surface the problem in the status bar
                self.attributor.error = "Process attribution unavailable: %s" % e
            if cycle % 10 == 0:
                try:
                    self.attributor.names.services = read_services()
                except Exception:
                    pass  # service names are a nicety; process names still work
            cycle += 1
            self.stop_evt.wait(1.0)


