class Card(tk.Frame):
    """A rounded panel. Put children in card.body. Sizes itself to its content."""

    def __init__(self, parent, pad=12, radius=14):
        super().__init__(parent, bd=0, highlightthickness=0)
        self.radius, self.colors, self._shape = radius, THEMES["light"], None
        self._cv = tk.Canvas(self, bd=0, highlightthickness=0)
        self._cv.place(x=0, y=0, relwidth=1, relheight=1)
        self.body = ttk.Frame(self, style="Card.TFrame")
        self.body.pack(fill="both", expand=True, padx=pad, pady=pad)
        self._cv.bind("<Configure>", self._draw)
        _register(self)
        self.apply(self.colors)

    def _draw(self, _e=None):
        w, h = self._cv.winfo_width(), self._cv.winfo_height()
        if w < 8 or h < 8:
            return
        if self._shape:
            self._cv.delete(self._shape)
        self._shape = round_rect(self._cv, 1, 1, w - 2, h - 2, self.radius, fill=self.colors["panel"],
                                 outline=self.colors["border"])

    def apply(self, t):
        self.colors = t
        self.configure(bg=t["bg"])
        self._cv.configure(bg=t["bg"])
        self._draw()


class RButton(tk.Canvas):
    """Rounded button with hover, pressed, disabled and keyboard-focus states (Space/Enter activate)."""

    def __init__(self, parent, text, command=None, kind="normal", on="panel"):
        super().__init__(parent, highlightthickness=0, bd=0, takefocus=1)
        self.text, self.command, self.kind, self.on = text, command, kind, on
        self.colors = THEMES["light"]
        self._font = tkfont.nametofont("TkDefaultFont")
        self._bold = self._font.copy()
        self._bold.configure(weight="bold")
        self._hover = self._down = self._focus = self._disabled = False
        ls = self._font.metrics("linespace")
        pad = int(ls * 0.8)
        self.configure(width=self._bold.measure(text) + 2 * pad, height=ls + int(ls * 0.7))
        for ev, fn in (("<Enter>", self._enter), ("<Leave>", self._leave), ("<ButtonPress-1>", self._press),
                       ("<ButtonRelease-1>", self._release), ("<FocusIn>", self._fin), ("<FocusOut>", self._fout),
                       ("<space>", self._key), ("<Return>", self._key), ("<Configure>", lambda e: self._draw())):
            self.bind(ev, fn)
        _register(self)
        self._draw()

    def _enter(self, _e):
        self._hover = True
        self._draw()

    def _leave(self, _e):
        self._hover = self._down = False
        self._draw()

    def _press(self, _e):
        if not self._disabled:
            self.focus_set()
            self._down = True
            self._draw()

    def _release(self, e):
        was = self._down
        self._down = False
        self._draw()
        if was and 0 <= e.x <= self.winfo_width() and 0 <= e.y <= self.winfo_height():
            self.invoke()

    def _fin(self, _e):
        self._focus = True
        self._draw()

    def _fout(self, _e):
        self._focus = False
        self._draw()

    def _key(self, _e):
        self.invoke()
        return "break"

    def invoke(self):
        if not self._disabled and self.command:
            self.command()

    def state(self, spec=None):
        if spec is None:
            return ("disabled",) if self._disabled else ()
        for s in spec:
            if s == "disabled":
                self._disabled = True
            elif s == "!disabled":
                self._disabled = False
        self._draw()

    def set_kind(self, kind):
        self.kind = kind
        self._draw()

    def apply(self, t):
        self.colors = t
        self._draw()

    def _draw(self):
        c = self.colors
        self.delete("all")
        w = self.winfo_width() if self.winfo_width() > 1 else int(self.cget("width"))
        h = self.winfo_height() if self.winfo_height() > 1 else int(self.cget("height"))
        self.configure(bg=c["panel"] if self.on == "panel" else c["bg"])
        if self._disabled:
            fill, fg, edge = c["btn_off"], c["muted"], c["border"]
        elif self.kind in ("primary", "tabsel"):
            fill = c["accent_hover"] if (self._hover or self._down) else c["accent"]
            fg, edge = c["accent_fg"], fill
        elif self.kind == "flat":
            fill = c["btn_hover"] if (self._hover or self._down) else (c["panel"] if self.on == "panel" else c["bg"])
            fg, edge = c["fg"], fill
        else:
            fill = c["btn_hover"] if (self._hover or self._down) else c["btn"]
            fg, edge = c["fg"], c["border"]
        if self._focus and not self._disabled:
            edge = c["accent"]
        round_rect(self, 1, 1, w - 2, h - 2, min(10, h // 2), fill=fill, outline=edge, width=2 if self._focus else 1)
        font = self._bold if self.kind in ("primary", "tabsel") else self._font
        self.create_text(w / 2, h / 2, text=self.text, fill=fg, font=font)


class TabView(ttk.Frame):
    """Pill-style tab bar. Same small API the app uses from ttk.Notebook: add, select, index, <<NotebookTabChanged>>."""

    def __init__(self, parent):
        super().__init__(parent)
        self.bar = ttk.Frame(self)
        self.bar.pack(fill="x", pady=(0, 10))
        self.stage = ttk.Frame(self)
        self.stage.pack(fill="both", expand=True)
        self.frames, self.buttons, self.current = [], [], None

    def add(self, frame, text):
        btn = RButton(self.bar, text, command=lambda f=frame: self.select(f), kind="tab", on="bg")
        btn.pack(side="left", padx=(0, 8))
        btn.bind("<Right>", lambda e: self._step(1))
        btn.bind("<Left>", lambda e: self._step(-1))
        frame.place(in_=self.stage, x=0, y=0, relwidth=1, relheight=1)
        self.frames.append(frame)
        self.buttons.append(btn)
        if self.current is None:
            self.select(frame)

    def select(self, frame=None):
        if frame is None:
            return str(self.current) if self.current is not None else ""
        if isinstance(frame, int):
            frame = self.frames[frame]
        if frame is self.current:
            return None
        self.current = frame
        self.tk.call("raise", frame._w)
        for f, b in zip(self.frames, self.buttons):
            b.set_kind("tabsel" if f is frame else "tab")
        self.event_generate("<<NotebookTabChanged>>")
        return None

    def index(self, what="current"):
        return self.frames.index(self.current)

    def _step(self, d):
        i = (self.index() + d) % len(self.frames)
        self.select(self.frames[i])
        self.buttons[i].focus_set()
        return "break"


def _tag_for(proto: str) -> str:
    if proto == "TCP":
        return "tcp"
    if proto == "UDP":
        return "udp"
    if proto in ("DNS", "MDNS"):
        return "dns"
    if proto in ("ICMP", "ICMPv6"):
        return "icmp"
    if proto == "ARP":
        return "arp"
    if proto == "Malformed" or proto.startswith("Link"):
        return "err"
    return "other"


