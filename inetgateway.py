class Pipeline:
    """Runs in the capture thread: decode, attribute, truncate, enqueue (bounded)."""

    def __init__(self, linktype, snaplen, out_queue, attributor=None):
        self.linktype, self.snaplen, self.q, self.attributor = linktype, snaplen, out_queue, attributor
        self.dropped = 0

    def feed(self, ts: float, data: bytes, wirelen: int):
        d = decode(data, self.linktype)
        proc = attr = ""
        if self.attributor is not None and d.l4:
            proc, attr = self.attributor.lookup(d)
        try:
            self.q.put_nowait(Packet(ts, bytes(data[:self.snaplen]), wirelen, d, proc, attr))
        except queue.Full:
            self.dropped += 1


class RawSocketBackend:
    label = "Raw socket (IPv4 only, no loopback, needs Administrator)"

    def __init__(self, ip: str):
        self.ip, self.linktype, self.sock = ip, LINK_RAW, None

    def open(self):
        s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_IP)
        try:
            s.bind((self.ip, 0))
            s.setsockopt(socket.IPPROTO_IP, socket.IP_HDRINCL, 1)
            s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4 * 1024 * 1024)
            s.ioctl(socket.SIO_RCVALL, socket.RCVALL_ON)
            s.settimeout(0.5)
        except Exception:
            s.close()
            raise
        self.sock = s

    def run(self, feed, stop: threading.Event):
        while not stop.is_set():
            try:
                data = self.sock.recv(65535)
            except socket.timeout:
                continue
            feed(time.time(), data, len(data))

    def close(self):
        if self.sock:
            try:
                self.sock.ioctl(socket.SIO_RCVALL, socket.RCVALL_OFF)
            except Exception:
                pass
            self.sock.close()
            self.sock = None


class LinuxPacketBackend:
    """AF_PACKET socket: Ethernet frames, IPv4/IPv6/ARP and the loopback interface. Needs root or CAP_NET_RAW."""
    label = "Linux AF_PACKET (Ethernet frames, IPv4/IPv6/ARP, loopback; needs root or CAP_NET_RAW)"

    def __init__(self, ifname: str):
        self.ifname, self.linktype, self.sock, self.loop = ifname, LINK_ETHERNET, None, False

    def open(self):
        if not re.match(r"^[A-Za-z0-9_.:@-]{1,15}$", self.ifname):
            raise OSError("Unexpected interface name")
        try:
            hatype = int(_read_text("/sys/class/net/%s/type" % self.ifname).strip() or "1")
        except ValueError:
            hatype = 1
        if hatype in (1, 772):          # Ethernet, loopback (loopback frames are Ethernet-shaped)
            self.linktype = LINK_ETHERNET
        elif hatype in (65534, 512):    # tun / ppp: raw IP packets
            self.linktype = LINK_RAW
        else:
            raise OSError("Unsupported interface type %d for %s" % (hatype, self.ifname))
        self.loop = hatype == 772
        s = socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(3))  # ETH_P_ALL
        try:
            s.bind((self.ifname, 0))
            s.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4 * 1024 * 1024)
            s.settimeout(0.5)
        except Exception:
            s.close()
            raise
        self.sock = s

    def run(self, feed, stop: threading.Event):
        while not stop.is_set():
            try:
                data, addr = self.sock.recvfrom(65535)
            except socket.timeout:
                continue
            if self.loop and addr[2] == 4:   # PACKET_OUTGOING: on loopback every packet also arrives as incoming
                continue
            feed(time.time(), data, len(data))

    def close(self):
        if self.sock:
            self.sock.close()
            self.sock = None


