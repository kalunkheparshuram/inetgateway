    def intel_check(self, text):
        kind, value = classify_indicator(text, allow_private=self.demo)
        if not self.vt_on():
            raise ValueError("Save an API key, then tick 'Enable VirusTotal lookups' first.")
        out = self.intel.submit(kind, value, ctx="manual check", manual=True)
        return {"queued": "Queued. The result appears below (your rate limit applies).",
                "cached": "Shown from the local cache; no request was sent.",
                "duplicate": "Already queued.", "full": "The lookup queue is full; try again shortly."}[out]

    def intel_clear(self):
        self.intel_cache.clear()
        self._intel_hits.clear()

    def intel_label(self, ip):
        r = self.intel_cache.peek("ip", ip)
        if not r:
            return ""
        return "VT %d/%d" % (r["mal"] + r["sus"], engines(r)) if r["status"] == "ok" else "VT: no data"

    def _intel_feed(self):
        s = self.vt_settings()
        if not (s["vt_enabled"] and self._vt_key):
            return
        svc, seen, budget = self.intel, self._intel_seen, 20
        if s["vt_auto_ip"]:
            for f in list(self.stats.flows.values()):
                ip = f.remote
                if ip in seen:
                    continue
                if not (self.demo or is_public_ip(ip)):
                    seen.add(ip)
                    continue
                if budget <= 0:
                    break
                if svc.submit("ip", ip, ctx=f.app) != "full":
                    seen.add(ip)
                    budget -= 1
        if s["vt_auto_domain"]:
            for name in list(self.dns_map.values()):
                key = "d:" + name
                if key in seen:
                    continue
                try:
                    kind, val = classify_indicator(name, allow_private=self.demo)
                except ValueError:
                    seen.add(key)
                    continue
                if budget <= 0:
                    break
                if svc.submit("domain", val, ctx="DNS answer") != "full":
                    seen.add(key)
                    budget -= 1
        if s["vt_auto_hash"] and self.attributor is not None:
            for path in list(self.attributor.names.paths):
                key = "p:" + path
                if key in seen:
                    continue
                if path.startswith("\\\\"):  # network shares: skip, could be slow
                    seen.add(key)
                    continue
                if budget <= 0:
                    break
                if svc.submit("path", path, ctx=ntpath.basename(path)) != "full":
                    seen.add(key)
                    budget -= 1
        if len(seen) > 20000:
            seen.clear()

    def _drain_intel(self):
        while True:
            try:
                res = self.intel_results.get_nowait()
            except queue.Empty:
                return
            self.intel_view.add_result(res)
            sev = severity(res)
            if sev in ("High", "Low", "Review"):
                self._intel_hits.add((res["kind"], res["q"]))
                if sev == "High":
                    self.notice = "Threat intel: High detection for %s %s" % (res["kind"], res["q"])

    # ---- capture control
    def _entry(self):
        label = self.iface_var.get()
        return next((i for i in self.ifaces if i["label"] == label), None)

    def start(self):
        if self.running:
            return
        entry = self._entry()
        if entry is None:
            messagebox.showinfo(APP_NAME, "No capture interface found.\n\nInstall Npcap (optional) or run as Administrator for the raw-socket backend.")
            return
        if len(self.store) and not messagebox.askokcancel(APP_NAME, "Starting a new capture clears the current packets. Continue?"):
            return
        if entry["kind"] == "demo":
            backend = DemoBackend()
        elif entry["kind"] == "npcap":
            backend = NpcapBackend(entry["name"], self.cfg["snaplen"], self.cfg["promiscuous"])
        elif entry["kind"] == "linux":
            backend = LinuxPacketBackend(entry["name"])
        else:
            backend = RawSocketBackend(entry["name"])
        try:
            backend.open()
        except OSError as e:
            self._open_failed(entry, e)
            return
        except Exception as e:
            messagebox.showerror(APP_NAME, "Could not start capture: %s" % e)
            return
        self.clear(force=True)
        if entry["kind"] == "raw":
            self.stats.base_local.add(entry["name"])
        self.stats.set_local(self.attributor.local_addrs if self.attributor else ())
        self.backend, self.linktype = backend, backend.linktype
        self.cfg["interface"] = entry["label"]
        save_config(self.cfg)
        self.pipeline = Pipeline(backend.linktype, self.cfg["snaplen"], self.q, self.attributor)
        self.stop_evt = threading.Event()
        if self.attributor is not None and not self.demo:
            self.refresher = TableRefresher(self.attributor)
            self.refresher.start()
        self.thread = threading.Thread(target=self._run, args=(backend, self.pipeline, self.stop_evt), daemon=True)
        self.running = True
        self.thread.start()
        self.btn_start.state(["disabled"])
        self.btn_stop.state(["!disabled"])
        self.notice = "Capturing via: " + backend.label
        if self.attributor is None and not self.demo:
            self.notice += " (no process attribution)"

    def _run(self, backend, pipeline, stop_evt):
        try:
            backend.run(pipeline.feed, stop_evt)
        except Exception as e:
            self.msgs.put(("error", "Capture stopped: %s" % e))
        finally:
            try:
                backend.close()
            finally:
                self.msgs.put(("stopped", ""))

    def _open_failed(self, entry, e):
        winerr = getattr(e, "winerror", None)
        if entry["kind"] == "raw" and (isinstance(e, PermissionError) or winerr in (10013, 5)):
            messagebox.showerror(APP_NAME, "Administrator rights are required for raw-socket capture.\n\n"
                                 "Use Capture > Restart as administrator, or install Npcap and pick an Npcap interface.")
        elif entry["kind"] == "linux" and isinstance(e, PermissionError):
            messagebox.showerror(APP_NAME, "Live capture on Linux needs root or the CAP_NET_RAW capability.\n\n"
                                 "Start the program with:  sudo -E inetgateway\n(see the README for details).")
        else:
            messagebox.showerror(APP_NAME, "Could not start capture:\n%s" % e)

    def stop(self):
        if self.running and self.stop_evt:
            self.stop_evt.set()
            self.btn_stop.state(["disabled"])
            self.notice = "Stopping..."

    def _finish_stop(self):
        self.running = False
        if self.refresher:
            self.refresher.stop_evt.set()
            self.refresher = None
        self.btn_start.state(["!disabled"])
        self.btn_stop.state(["disabled"])

    def clear(self, force=False):
        self.store.clear()
        while True:
            try:
                self.q.get_nowait()
            except queue.Empty:
                break
        self.tree.delete(*self.tree.get_children())
        self.rows.clear()
        self._clear_detail()
        self.t0 = None
        self.stats.reset()
        self.dns_map.clear()
        self.dash.reset()
        if self.pipeline:
            self.pipeline.dropped = 0

    def restart_admin(self):
        if is_admin():
            messagebox.showinfo(APP_NAME, "Already running as administrator.")
            return
        import subprocess
        frozen = getattr(sys, "frozen", False)
        args = sys.argv[1:] if frozen else [os.path.abspath(sys.argv[0])] + sys.argv[1:]
        rc = ctypes.windll.shell32.ShellExecuteW(None, "runas", sys.executable, subprocess.list2cmdline(args), None, 1)
        if rc > 32:
            self.on_close()

    # ---- display
    def _row(self, p: Packet):
        return (p.no, "%.6f" % (p.ts - self.t0), p.src, p.dst, p.proto, p.wirelen, p.proc, p.info)

    def _insert(self, p: Packet):
        iid = str(p.no)
        self.tree.insert("", "end", iid=iid, values=self._row(p), tags=(_tag_for(p.proto),))
        self.rows.append(iid)
        while len(self.rows) > DISPLAY_CAP:
            old = self.rows.popleft()
            if self.tree.exists(old):
                self.tree.delete(old)

    def _tick(self):
        try:
            n, last = 0, None
            while n < DRAIN_PER_TICK:
                try:
                    p = self.q.get_nowait()
                except queue.Empty:
                    break
                n += 1
                if self.t0 is None:
                    self.t0 = p.ts
                self.store.add(p)
                self.stats.add(p)
                if p.answers:
                    self._learn(p.answers)
                if self.filter_fn(p):
                    self._insert(p)
                    last = str(p.no)
            if last and self.autoscroll.get():
                self.tree.see(last)
            while True:
                try:
                    kind, text = self.msgs.get_nowait()
                except queue.Empty:
                    break
                if kind == "error":
                    self.notice = text
                    messagebox.showerror(APP_NAME, text)
                elif kind == "stopped":
                    self._finish_stop()
                    self.notice = self.notice if self.notice.startswith("Capture stopped") else "Stopped."
            self._drain_intel()
            self.tick_n += 1
            if self.tick_n % 10 == 0:
                if self.running and self.attributor is not None:
                    self.stats.set_local(self.attributor.local_addrs)
                self._intel_feed()
                self._update_status()
                self.dash.refresh()
                if self.nb.select() == str(self.tab_intel):
                    self.intel_view.refresh_status()
        finally:
            if not self._closing:
                self._after_id = self.root.after(TICK_MS, self._tick)

    def _learn(self, answers):
        for name, ip in answers:
            self.dns_map[ip] = name
        while len(self.dns_map) > 5000:
            del self.dns_map[next(iter(self.dns_map))]

    def _update_status(self):
        drops = self.pipeline.dropped if self.pipeline else 0
        extra = ""
        if self.attributor is not None and self.attributor.error:
            extra = "  |  " + self.attributor.error
        hits = "   Threat intel: %d with detections" % len(self._intel_hits) if self._intel_hits else ""
        self.status.configure(text="Packets: %d shown / %d stored / %d seen   Viewer drops: %d   %s%s%s" % (
            len(self.rows), len(self.store), self.store.total, drops, self.notice, hits, extra))

    def apply_filter(self):
        try:
            fn = compile_filter(self.filter_var.get())
        except ValueError as e:
            self.filter_entry.configure(style="Bad.TEntry")
            self.notice = "Invalid filter: %s" % e
            self._update_status()
            return
        self.filter_entry.configure(style="TEntry")
        self.filter_fn = fn
        self.tree.delete(*self.tree.get_children())
        self.rows.clear()
        matches = [p for p in self.store if fn(p)][-DISPLAY_CAP:]
        for p in matches:
            self._insert(p)
        self.notice = "Filter applied." if self.filter_var.get().strip() else "Filter cleared."
        self._update_status()

    def _clear_detail(self):
        self.detail.delete(*self.detail.get_children())
        self.hex.configure(state="normal")
        self.hex.delete("1.0", "end")
        self.hex.configure(state="disabled")

    def on_select(self, _e=None):
        sel = self.tree.selection()
        if not sel:
            return
        p = self.store.get(int(sel[0]))
        self._clear_detail()
        if p is None:
            self.detail.insert("", "end", text="Packet is no longer in the buffer.")
            return
        d = decode(p.raw, self.linktype, detail=True)
        when = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(p.ts)) + ".%03d" % int((p.ts % 1) * 1000)
        frame = ["Arrival time: " + when, "On the wire: %d bytes" % p.wirelen, "Stored: %d bytes (snap length)" % len(p.raw)]
        if p.proc:
            frame.append("Process: %s" % p.proc)
            frame.append("Attribution: %s" % p.attr)
        elif p.l4 and self.attributor is not None:
            frame.append("Process: not attributed (no matching entry in the connection table snapshot)")
        elif p.l4:
            frame.append("Process: attribution not available in this mode")
        layers = [("Frame %d" % p.no, frame)] + d.layers
        for title, lines in layers:
            node = self.detail.insert("", "end", text=title, open=True)
            for ln in lines:
                self.detail.insert(node, "end", text=ln)
        self.hex.configure(state="normal")
        self.hex.insert("1.0", hexdump(p.raw))
        self.hex.configure(state="disabled")

    def on_context(self, e):
        iid = self.tree.identify_row(e.y)
        if iid:
            self.tree.selection_set(iid)
            self.menu_ctx.tk_popup(e.x_root, e.y_root)

    def _selected(self):
        sel = self.tree.selection()
        return self.store.get(int(sel[0])) if sel else None

    def _copy(self, what):
        p = self._selected()
        if not p:
            return
        text = {"src": p.src, "dst": p.dst}.get(what) or "\t".join(str(x) for x in self._row(p))
        self.root.clipboard_clear()
        self.root.clipboard_append(text)

    def _filter_on(self, which):
        p = self._selected()
        if p and (p.src if which == "src" else p.dst):
            self.filter_var.set("%s==%s" % (which, p.src if which == "src" else p.dst))
            self.apply_filter()

