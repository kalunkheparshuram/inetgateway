def parse_vt_response(kind: str, value: str, status: int, body: bytes, now: float) -> dict:
    res = {"kind": kind, "q": value, "t": now, "status": "error", "mal": 0, "sus": 0, "har": 0, "und": 0,
           "rep": None, "owner": "", "country": "", "note": ""}
    if status == 200:
        try:
            attrs = json.loads(body.decode("utf-8", "replace"))["data"]["attributes"]
            stats = attrs.get("last_analysis_stats") or {}
            if not isinstance(attrs, dict) or not isinstance(stats, dict):
                raise TypeError
        except (ValueError, KeyError, TypeError, AttributeError):
            res["note"] = "Unexpected response format"
            return res

        def num(k):
            v = stats.get(k, 0)
            return v if isinstance(v, int) and not isinstance(v, bool) and 0 <= v <= 10000 else 0
        res.update(status="ok", mal=num("malicious"), sus=num("suspicious"), har=num("harmless"), und=num("undetected"))
        rep = attrs.get("reputation")
        if isinstance(rep, int) and not isinstance(rep, bool) and -100000 <= rep <= 100000:
            res["rep"] = rep
        if kind == "ip":
            owner = attrs.get("as_owner")
        elif kind == "file":
            owner = attrs.get("meaningful_name") or attrs.get("type_description")
        else:
            owner = attrs.get("registrar")
        res["owner"] = safe_text(owner or "", 60) if isinstance(owner, str) or owner is None else ""
        country = attrs.get("country")
        res["country"] = safe_text(country, 8) if isinstance(country, str) else ""
        if res["mal"] + res["sus"] + res["har"] + res["und"] == 0:
            res["note"] = "VirusTotal has no analysis results for this yet"
    elif status == 404:
        res["status"] = "notfound"
    elif status in (401, 403):
        res["status"] = "badkey"
        res["note"] = "VirusTotal rejected the API key"
    elif status == 429:
        res["status"] = "ratelimited"
        res["note"] = "VirusTotal rate limit hit"
    elif status == 0:
        res["note"] = safe_text(body or b"network error", 120)
    else:
        res["note"] = "HTTP %d" % status
    return res


def engines(res: dict) -> int:
    return res["mal"] + res["sus"] + res["har"] + res["und"]


def severity(res: dict) -> str:
    """High: 3+ engines say malicious. Low: 1-2 (could be false positives). Review: only 'suspicious'. None: no detections."""
    if res.get("status") != "ok":
        return "Unknown"
    if res["mal"] >= 3:
        return "High"
    if res["mal"] >= 1:
        return "Low"
    if res["sus"] >= 1:
        return "Review"
    return "None"


def verdict_text(res: dict) -> str:
    st = res.get("status")
    if st == "ok":
        return "%d malicious, %d suspicious of %d engines" % (res["mal"], res["sus"], engines(res))
    return {"notfound": "Not in VirusTotal (no verdict)", "badkey": "API key rejected",
            "ratelimited": "Rate limited", "dailylimit": "Daily limit reached"}.get(st, "Lookup failed")


def sha256_file(path: str, limit: int = 512 * 1024 * 1024):
    try:
        if not os.path.isfile(path) or os.path.getsize(path) > limit:
            return None
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1024 * 1024), b""):
                h.update(chunk)
        return h.hexdigest()
    except OSError:
        return None


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None  # never follow redirects: the API key must only ever go to the API host


def default_fetch(url: str, key: str):
    """HTTPS GET to the VirusTotal API only. Returns (status, body); status 0 means a network error."""
    if not url.startswith(VT_API):
        return 0, b"refused: not a VirusTotal API URL"
    req = urllib.request.Request(url, headers={"x-apikey": key, "accept": "application/json",
                                               "User-Agent": "%s/%s" % (APP_NAME, __version__)})
    opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ssl.create_default_context()), _NoRedirect())
    try:
        with opener.open(req, timeout=15) as r:
            return r.status, r.read(1_000_001)[:1_000_000]
    except urllib.error.HTTPError as e:
        return e.code, b""
    except (urllib.error.URLError, OSError, ssl.SSLError, ValueError) as e:
        return 0, ("Network error: %s" % getattr(e, "reason", e)).encode("utf-8", "replace")


