def _is_bm(ip: str) -> bool:
    if ":" in ip:
        return ip.startswith("ff")
    try:
        first = int(ip.split(".", 1)[0])
    except ValueError:
        return False
    return 224 <= first <= 239 or ip.endswith(".255")


def parse_tasklist_svc(text: str) -> dict:
    """Parse `tasklist /svc /fo csv /nh` output into {pid: 'Svc1, Svc2'}."""
    out = {}
    for row in csv.reader(io.StringIO(text)):
        if len(row) < 3 or not row[1].isdigit():
            continue
        svcs = row[2].strip()
        if not svcs or svcs.upper() == "N/A":
            continue
        label = safe_text(svcs.replace(",", ", "), 200)
        out[int(row[1])] = label if len(label) <= 60 else label[:57] + "..."
    return out


