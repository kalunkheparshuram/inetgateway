    # ---- results
    @staticmethod
    def _iid(res):
        return "r:%s:%s" % (res["kind"], res["q"])

    def add_result(self, res):
        if res.get("status") in ("ratelimited",):
            return
        iid = self._iid(res)
        old = self.results.get(iid)
        res = dict(res)
        if old and not res.get("ctx"):
            res["ctx"] = old.get("ctx", "")
        self.results[iid] = res
        while len(self.results) > 1000:
            del self.results[next(iter(self.results))]
        self._render()

    def _row(self, res):
        ok = res.get("status") == "ok"
        return (fmt_time(res["t"]), {"ip": "IP", "domain": "Domain", "file": "File"}.get(res["kind"], res["kind"]),
                res["q"], severity(res) if ok else "n/a", verdict_text(res) + (" (" + res["note"] + ")" if res.get("note") and not ok else ""),
                (res.get("owner") or "") + ((" / " + res["country"]) if res.get("country") else ""), res.get("ctx", ""))

    def _render(self):
        want = []
        for iid, res in sorted(self.results.items(), key=lambda kv: kv[1]["t"], reverse=True):
            sev = severity(res)
            if self.only_hits.get() and sev not in ("High", "Low", "Review"):
                continue
            want.append((iid, self._row(res), sev if sev in ("High", "Low", "Review") else ""))
        existing = set(self.tree.get_children())
        for iid, vals, tag in want:
            if iid in existing:
                self.tree.item(iid, values=vals, tags=(tag,) if tag else ())
            else:
                self.tree.insert("", "end", iid=iid, values=vals, tags=(tag,) if tag else ())
        for iid in existing.difference(i for i, _, _ in want):
            self.tree.delete(iid)
        order = [i for i, _, _ in want]
        if list(self.tree.get_children()) != order:
            for idx, iid in enumerate(order):
                self.tree.move(iid, "", idx)

    def _on_select(self, _e=None):
        r = self._selected()
        lines = []
        if r:
            lines = ["Indicator: %s (%s)" % (r["q"], r["kind"]), "Result: " + verdict_text(r)]
            if r.get("status") == "ok":
                lines.append("Severity: %s   (High = 3+ engines say malicious; Low = 1-2, possible false positive; "
                             "Review = only 'suspicious')" % severity(r))
                lines.append("Engines: %d malicious, %d suspicious, %d harmless, %d undetected" % (r["mal"], r["sus"], r["har"], r["und"]))
                if r.get("rep") is not None:
                    lines.append("VirusTotal reputation score: %d" % r["rep"])
            if r.get("owner"):
                lines.append("Owner / name: %s %s" % (r["owner"], r.get("country") or ""))
            if r.get("ctx"):
                lines.append("Seen as: " + r["ctx"])
            if r.get("note"):
                lines.append("Note: " + r["note"])
            lines.append(CAUTION)
        self.detail.configure(state="normal")
        self.detail.delete("1.0", "end")
        self.detail.insert("1.0", "\n".join(lines))
        self.detail.configure(state="disabled")

    def refresh_status(self):
        app = self.app
        who = "administrator" if os.name == "nt" else "root"
        self.priv_lbl.configure(text="Running as %s: %s" % (who, "yes" if is_admin() else "no"))
        if app.demo:
            ks = "DEMO: canned results, no network, no key used"
        elif app.keystore.exists():
            ks = "API key saved (%s)" % ("encrypted for this Windows user" if app.keystore.scheme == "dpapi"
                                          else "NOT encrypted: this is not Windows")
        else:
            ks = "No API key saved"
        self.key_status.configure(text=ks)
        svc = app.intel
        used = app.intel_cache.used_today()
        self.state_lbl.configure(text="Status: %s   |   Queue: %d   |   Used today: %d / %d" % (
            svc.status if app.vt_on() else "Off", svc.queue_size(), used, app.vt_settings()["vt_daily"]))

    def reset_results(self, results):
        self.results.clear()
        for r in results:
            self.results[self._iid(r)] = dict(r)
        self._render()


