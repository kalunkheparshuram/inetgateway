class PacketStore:
    """Bounded ring of packets with contiguous numbers; only the GUI thread touches it."""

    def __init__(self, maxlen: int):
        self._d = collections.deque(maxlen=maxlen)
        self.total = 0

    def add(self, pkt: Packet) -> int:
        self.total += 1
        pkt.no = self.total
        self._d.append(pkt)
        return pkt.no

    def get(self, no: int):
        if not self._d:
            return None
        idx = no - self._d[0].no
        return self._d[idx] if 0 <= idx < len(self._d) else None

    def clear(self):
        self._d.clear()
        self.total = 0

    def __len__(self):
        return len(self._d)

    def __iter__(self):
        return iter(self._d)


_LEN_RE = re.compile(r"^len(>=|<=|==|>|<)(\d{1,6})$")
_LEN_OPS = {">=": lambda a, b: a >= b, "<=": lambda a, b: a <= b, "==": lambda a, b: a == b,
            ">": lambda a, b: a > b, "<": lambda a, b: a < b}


def _norm_ip(v: str) -> str:
    return str(ipaddress.ip_address(v))  # raises ValueError on garbage


def _compile_token(tok: str):
    t = tok.lower()
    if t in ("tcp", "udp"):
        return lambda p: p.l4 == t
    if t in ("icmp", "icmpv6", "dns", "mdns", "arp", "igmp"):
        return lambda p: p.proto.lower() == t
    if t == "ipv4":
        return lambda p: p.ipver == 4
    if t == "ipv6":
        return lambda p: p.ipver == 6
    m = _LEN_RE.match(t)
    if m:
        fn, n = _LEN_OPS[m.group(1)], int(m.group(2))
        return lambda p: fn(p.wirelen, n)
    if "==" in tok:
        key, _, val = tok.partition("==")
        key = key.lower()
        if key in ("ip", "src", "dst"):
            v = _norm_ip(val)
            if key == "ip":
                return lambda p: p.src == v or p.dst == v
            if key == "src":
                return lambda p: p.src == v
            return lambda p: p.dst == v
        if key in ("port", "sport", "dport"):
            if not val.isdigit() or int(val) > 65535:
                raise ValueError("bad port")
            n = int(val)
            if key == "port":
                return lambda p: p.sport == n or p.dport == n
            if key == "sport":
                return lambda p: p.sport == n
            return lambda p: p.dport == n
        if key == "proc":
            v = val.lower()
            if not v:
                raise ValueError("empty process name")
            return lambda p: v in p.proc.lower()
        raise ValueError("unknown field '%s'" % key)
    return lambda p: t in p.src.lower() or t in p.dst.lower() or t in p.proc.lower() or t in p.info.lower()


def compile_filter(text: str):
    """Space-separated terms are ANDed; a leading '!' negates a term. Raises ValueError."""
    text = text.strip()
    if not text:
        return lambda p: True
    terms = []
    for tok in text.split():
        neg = tok.startswith("!")
        if neg:
            tok = tok[1:]
        if not tok:
            raise ValueError("empty term")
        terms.append((neg, _compile_token(tok)))
    return lambda p: all(fn(p) != neg for neg, fn in terms)


