def _is_public(ip) -> bool:
    # Python calls multicast "global"; it is not something VirusTotal (or anyone) has a reputation for.
    return bool(ip.is_global and not (ip.is_multicast or ip.is_reserved or ip.is_loopback
                                      or ip.is_link_local or ip.is_unspecified))


def is_public_ip(ip: str) -> bool:
    try:
        return _is_public(ipaddress.ip_address(ip))
    except ValueError:
        return False


def valid_api_key(key: str) -> bool:
    return bool(key) and _KEY_RE.match(key) is not None


def classify_indicator(text: str, allow_private: bool = False):
    """Return (kind, normalised value) for an IP, domain or file hash, or raise ValueError with a user message."""
    t = (text or "").strip()
    if not t or len(t) > 300:
        raise ValueError("Enter a public IP address, a domain name, or a file hash (MD5, SHA-1 or SHA-256).")
    try:
        ip = ipaddress.ip_address(t)
    except ValueError:
        ip = None
    if ip is not None:
        if not _is_public(ip) and not allow_private:
            raise ValueError("That is a private, local, multicast or reserved address. VirusTotal has no data about it.")
        return "ip", str(ip)
    if _HASH_RE.match(t):
        return "file", t.lower()
    d = t.lower().rstrip(".")
    if _DOMAIN_RE.match(d):
        if d.endswith(NON_PUBLIC_SUFFIXES) and not allow_private:
            raise ValueError("That looks like a local-only name. VirusTotal has no data about it.")
        return "domain", d
    raise ValueError("Enter a public IP address, a domain name, or a file hash (MD5, SHA-1 or SHA-256).")


