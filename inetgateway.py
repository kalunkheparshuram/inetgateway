UNATTRIBUTED = "(unattributed)"
MAX_APPS, MAX_FLOWS, SERIES_KEEP = 500, 5000, 600
_APP_RE = re.compile(r"^(.*) \((\d+)\)$")


def app_name(proc: str) -> str:
    """'chrome.exe (1234)' -> 'chrome.exe'; blank -> '(unattributed)'."""
    if not proc:
        return UNATTRIBUTED
    m = _APP_RE.match(proc)
    return m.group(1) if m else proc


def fmt_bytes(n) -> str:
    n = float(n)
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return ("%d %s" % (n, unit)) if unit == "B" else ("%.1f %s" % (n, unit))
        n /= 1024.0


def fmt_rate(n) -> str:
    return fmt_bytes(n) + "/s"


def fmt_time(ts: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(ts))


def nice_ceiling(v: float) -> float:
    if v <= 0:
        return 1.0
    exp = 10 ** math.floor(math.log10(v))
    for m in (1, 2, 5, 10):
        if v <= m * exp:
            return float(m * exp)
    return float(10 * exp)


def top_n_slices(items, n: int):
    items = sorted(((k, v) for k, v in items if v > 0), key=lambda kv: kv[1], reverse=True)
    out = items[:n]
    rest = sum(v for _, v in items[n:])
    if rest > 0:
        out.append(("Other", rest))
    return out


