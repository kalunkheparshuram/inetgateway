class AppStats:
    __slots__ = ("id", "name", "sent_pkts", "recv_pkts", "other_pkts", "sent_bytes", "recv_bytes",
                 "other_bytes", "conns", "dns_q", "dns_r", "first", "last", "remotes")

    def __init__(self, id_, name, ts):
        self.id, self.name, self.first, self.last = id_, name, ts, ts
        self.sent_pkts = self.recv_pkts = self.other_pkts = 0
        self.sent_bytes = self.recv_bytes = self.other_bytes = 0
        self.conns = self.dns_q = self.dns_r = 0
        self.remotes = set()

    @property
    def total_bytes(self):
        return self.sent_bytes + self.recv_bytes + self.other_bytes


class Flow:
    __slots__ = ("id", "app", "proto", "remote", "rport", "from_ip", "to_ip", "fwd_pkts", "fwd_bytes",
                 "rev_pkts", "rev_bytes", "first", "last", "conns")

    def __init__(self, id_, app, proto, remote, rport, from_ip, to_ip, ts):
        self.id, self.app, self.proto, self.remote, self.rport = id_, app, proto, remote, rport
        self.from_ip, self.to_ip, self.first, self.last = from_ip, to_ip, ts, ts
        self.fwd_pkts = self.fwd_bytes = self.rev_pkts = self.rev_bytes = self.conns = 0


class Stats:
    """Cumulative counters since capture start, independent of the bounded packet buffer.

    'Sent' = packets leaving this PC, 'Received' = packets arriving at it, decided by comparing
    addresses with the PC's own addresses. Application-level requests/responses inside encrypted
    traffic cannot be separated; DNS queries/responses are counted from DNS headers.
    """

    def __init__(self, local=()):
        self.base_local = set(local)
        self.local = set(local)
        self.reset()

    def reset(self):
        self.apps, self.flows, self.series, self.proto_bytes = {}, {}, {}, {}
        self.sent_pkts = self.recv_pkts = self.other_pkts = 0
        self.sent_bytes = self.recv_bytes = self.other_bytes = 0
        self._next_id = 1
        self.last_ts = 0.0

    def set_local(self, addrs):
        self.local = self.base_local | set(addrs)

    def _id(self):
        self._next_id += 1
        return self._next_id

    def add(self, p):
        size, ts = p.wirelen, p.ts
        self.last_ts = max(self.last_ts, ts)
        if not p.ipver or not self.local:
            dirn = "other"
        elif p.src in self.local:
            dirn = "out"
        elif p.dst in self.local or _is_bm(p.dst):
            dirn = "in"
        else:
            dirn = "other"
        name = app_name(p.proc)
        a = self.apps.get(name)
        if a is None:
            a = self.apps[name] = AppStats(self._id(), name, ts)
            if len(self.apps) > MAX_APPS:
                for victim in sorted(self.apps.values(), key=lambda x: x.last)[:50]:
                    del self.apps[victim.name]
        a.last = ts
        if dirn == "out":
            a.sent_pkts += 1
            a.sent_bytes += size
            self.sent_pkts += 1
            self.sent_bytes += size
        elif dirn == "in":
            a.recv_pkts += 1
            a.recv_bytes += size
            self.recv_pkts += 1
            self.recv_bytes += size
        else:
            a.other_pkts += 1
            a.other_bytes += size
            self.other_pkts += 1
            self.other_bytes += size
        syn_out = dirn == "out" and (p.tcpflags & 0x02) and not (p.tcpflags & 0x10)
        if syn_out:
            a.conns += 1
        if p.dns == "q":
            a.dns_q += 1
        elif p.dns == "r":
            a.dns_r += 1
        self.proto_bytes[p.proto] = self.proto_bytes.get(p.proto, 0) + size
        if dirn in ("out", "in"):
            sec = int(ts)
            b = self.series.get(sec)
            if b is None:
                b = self.series[sec] = [0, 0]
                if len(self.series) > SERIES_KEEP * 2:
                    for k in [k for k in self.series if k < sec - SERIES_KEEP]:
                        del self.series[k]
            b[0 if dirn == "out" else 1] += size
        if not p.ipver:
            return
        remote = p.dst if dirn in ("out", "other") else p.src
        if len(a.remotes) < 2000:
            a.remotes.add(remote)
        if dirn == "out":
            rport = p.dport
        elif dirn == "in":
            rport = p.sport
        else:
            ports = [x for x in (p.sport, p.dport) if x is not None]
            rport = min(ports) if ports else None
        lo, hi = (p.src, p.dst) if p.src <= p.dst else (p.dst, p.src)
        key = (name, p.proto, lo, hi, rport)
        fl = self.flows.get(key)
        if fl is None:
            fl = self.flows[key] = Flow(self._id(), name, p.proto, remote, rport, p.src, p.dst, ts)
            if len(self.flows) > MAX_FLOWS:
                keep = sorted(self.flows.items(), key=lambda kv: kv[1].last, reverse=True)[:int(MAX_FLOWS * 0.9)]
                self.flows = dict(keep)
        fl.last = ts
        if p.src == fl.from_ip:
            fl.fwd_pkts += 1
            fl.fwd_bytes += size
        else:
            fl.rev_pkts += 1
            fl.rev_bytes += size
        if syn_out:
            fl.conns += 1

    def apps_sorted(self):
        return sorted(self.apps.values(), key=lambda a: a.total_bytes, reverse=True)

    def flows_sorted(self, app=None, limit=300):
        fl = [f for f in self.flows.values() if app is None or f.app == app]
        fl.sort(key=lambda f: f.last, reverse=True)
        return fl[:limit]

    def series_window(self, end_ts, n=120):
        end = int(end_ts)
        sent, recv = [], []
        for s in range(end - n + 1, end + 1):
            b = self.series.get(s)
            sent.append(b[0] if b else 0)
            recv.append(b[1] if b else 0)
        return sent, recv

    def remote_bytes(self):
        agg = {}
        for f in self.flows.values():
            agg[f.remote] = agg.get(f.remote, 0) + f.fwd_bytes + f.rev_bytes
        return agg


