# --- Linux process attribution: /proc/net/{tcp,udp}[6] gives sockets, /proc/<pid>/fd gives their owners --------

def _linux_addr(h: str) -> str:
    b = bytes.fromhex(h)
    if len(b) == 4:
        return socket.inet_ntoa(b[::-1])
    return str(ipaddress.IPv6Address(b"".join(b[i:i + 4][::-1] for i in range(0, 16, 4))))


def parse_proc_net(text: str, udp: bool):
    """/proc/net/tcp* -> {(laddr, lport, raddr, rport): inode}; udp -> {lport: [(laddr, inode)]}. Bad lines are skipped."""
    out = {}
    for line in text.splitlines()[1:]:
        f = line.split()
        if len(f) < 10:
            continue
        try:
            la, lp = f[1].split(":")
            ra, rp = f[2].split(":")
            inode = int(f[9])
            if inode == 0:
                continue  # TIME_WAIT and similar: no owner
            la, lport = _linux_addr(la), int(lp, 16)
            if udp:
                out.setdefault(lport, []).append((la, inode))
            else:
                out[(la, lport, _linux_addr(ra), int(rp, 16))] = inode
        except (ValueError, IndexError):
            continue
    return out


def linux_socket_owners() -> dict:
    """{socket inode: pid} for every process whose fd table we are allowed to read (all of them as root)."""
    owners = {}
    try:
        pids = [x for x in os.listdir("/proc") if x.isdigit()]
    except OSError:
        return owners
    for pid in pids:
        fd_dir = "/proc/%s/fd" % pid
        try:
            fds = os.listdir(fd_dir)
        except OSError:
            continue
        for fd in fds:
            try:
                link = os.readlink("%s/%s" % (fd_dir, fd))
            except OSError:
                continue
            if link.startswith("socket:["):
                try:
                    owners.setdefault(int(link[8:-1]), int(pid))
                except ValueError:
                    pass
    return owners


def _read_text(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _linux_read_connection_tables():
    """Same shape as the Windows reader. Sockets we cannot attribute get pid -1, so local addresses are still learned."""
    owners = linux_socket_owners()
    tcp, udp = {}, {}
    for name in ("tcp", "tcp6"):
        for key, ino in parse_proc_net(_read_text("/proc/net/" + name), False).items():
            tcp[key] = owners.get(ino, -1)
    for name in ("udp", "udp6"):
        for lport, lst in parse_proc_net(_read_text("/proc/net/" + name), True).items():
            udp.setdefault(lport, []).extend((la, owners.get(ino, -1)) for la, ino in lst)
    return tcp, udp


