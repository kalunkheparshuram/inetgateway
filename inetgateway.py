def write_pcap(path: str, packets, linktype: int, snaplen: int):
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, snaplen, linktype))
        for p in packets:
            sec = int(p.ts)
            f.write(struct.pack("<IIII", sec, int((p.ts - sec) * 1e6), len(p.raw), p.wirelen))
            f.write(p.raw)
    os.replace(tmp, path)


def read_pcap(path: str, max_packets: int = 500000):
    """Classic pcap only (not pcapng). Returns (linktype, snaplen, [(ts, bytes, wirelen)])."""
    with open(path, "rb") as f:
        gh = f.read(24)
        if len(gh) < 24:
            raise ValueError("not a pcap file")
        magics = {b"\xd4\xc3\xb2\xa1": ("<", 1e6), b"\xa1\xb2\xc3\xd4": (">", 1e6),
                  b"\x4d\x3c\xb2\xa1": ("<", 1e9), b"\xa1\xb2\x3c\x4d": (">", 1e9)}
        if gh[:4] not in magics:
            raise ValueError("not a classic pcap file (pcapng is not supported)")
        e, div = magics[gh[:4]]
        _, _, _, _, snaplen, network = struct.unpack(e + "HHiIII", gh[4:24])
        out = []
        while len(out) < max_packets:
            h = f.read(16)
            if len(h) < 16:
                break
            sec, frac, caplen, wirelen = struct.unpack(e + "IIII", h)
            if caplen > 262144:
                raise ValueError("corrupt record length")
            data = f.read(caplen)
            if len(data) < caplen:
                break
            out.append((sec + frac / div, data, wirelen))
    return network, snaplen, out


