    def open_pcap(self):
        if self.running:
            messagebox.showinfo(APP_NAME, "Stop the capture first.")
            return
        path = filedialog.askopenfilename(filetypes=[("pcap", "*.pcap"), ("All files", "*.*")])
        if not path:
            return
        try:
            lt, snap, pkts = read_pcap(path, self.cfg["max_packets"])
        except (OSError, ValueError) as e:
            messagebox.showerror(APP_NAME, "Could not open file: %s" % e)
            return
        if lt not in SUPPORTED_LINKTYPES:
            messagebox.showerror(APP_NAME, "Unsupported link type %d in this file." % lt)
            return
        self.clear(force=True)
        self.linktype = lt
        self.stats.local = set()  # a pcap file does not say which addresses were this PC's
        for ts, data, wl in pkts:
            if self.t0 is None:
                self.t0 = ts
            p = Packet(ts, data[:self.cfg["snaplen"]], wl, decode(data, lt))
            self.store.add(p)
            self.stats.add(p)
            if p.answers:
                self._learn(p.answers)
            if self.filter_fn(p):
                self._insert(p)
        self.notice = "Opened %s (%d packets). Process names and Sent/Received direction are not stored in pcap files." % (os.path.basename(path), len(pkts))
        self._update_status()

