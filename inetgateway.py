def _port(dword: int) -> int:
    return ((dword & 0xFF) << 8) | ((dword >> 8) & 0xFF)


def parse_tcp_table(buf: bytes, v6: bool) -> dict:
    """MIB_TCP(6)TABLE_OWNER_PID -> {(laddr, lport, raddr, rport): pid}"""
    out = {}
    if len(buf) < 4:
        return out
    n = struct.unpack_from("<I", buf, 0)[0]
    size = 56 if v6 else 24
    for i in range(min(n, (len(buf) - 4) // size)):
        pos = 4 + i * size
        if v6:
            la, _, lp, ra, _, rp, _, pid = struct.unpack_from("<16sII16sIIII", buf, pos)
            la, ra = str(ipaddress.IPv6Address(la)), str(ipaddress.IPv6Address(ra))
        else:
            _, la, lp, ra, rp, pid = struct.unpack_from("<I4sI4sII", buf, pos)
            la, ra = socket.inet_ntoa(la), socket.inet_ntoa(ra)
        out[(la, _port(lp), ra, _port(rp))] = pid
    return out


def parse_udp_table(buf: bytes, v6: bool) -> dict:
    """MIB_UDP(6)TABLE_OWNER_PID -> {lport: [(laddr, pid), ...]}"""
    out = {}
    if len(buf) < 4:
        return out
    n = struct.unpack_from("<I", buf, 0)[0]
    size = 28 if v6 else 12
    for i in range(min(n, (len(buf) - 4) // size)):
        pos = 4 + i * size
        if v6:
            la, _, lp, pid = struct.unpack_from("<16sIII", buf, pos)
            la = str(ipaddress.IPv6Address(la))
        else:
            la, lp, pid = struct.unpack_from("<4sII", buf, pos)
            la = socket.inet_ntoa(la)
        out.setdefault(_port(lp), []).append((la, pid))
    return out


class ProcessNames:
    TTL = 10.0  # seconds; PID reuse inside this window can mislabel a process (documented)

    def __init__(self, resolver):
        self._resolver = resolver
        self._cache = {}
        self.services = {}  # pid -> "Svc1, Svc2" (from tasklist /svc), refreshed in the background
        self.paths = {}     # executable path -> file name, for optional hash lookups

    def get(self, pid: int):
        now = time.monotonic()
        e = self._cache.get(pid)
        if e and now - e[0] < self.TTL:
            return e[1]
        if pid == 0:
            v = ("[System Idle]", "")
        elif pid == 4:
            v = ("System", "")
        else:
            path = self._resolver(pid) if self._resolver else None
            v = (ntpath.basename(path), path) if path else ("", "")
        if len(self._cache) > 2048:
            self._cache.clear()
        self._cache[pid] = (now, v)
        if v[1] and len(self.paths) < 4096:
            self.paths[v[1]] = v[0]
        return v


class Attributor:
    """Maps a decoded packet to a process using a periodic snapshot of the OS connection tables.

    TCP: exact 4-tuple match. UDP: local-port match only (weaker). Connections that
    start and end between two snapshots are never attributed. Unknown stays blank.
    """

    def __init__(self, names: ProcessNames):
        self.names = names
        self.tcp, self.udp = {}, {}
        self.local_addrs = set()
        self.error = ""

    def update(self, tcp: dict, udp: dict):
        la = {k[0] for k in tcp}
        for lst in udp.values():
            la.update(a for a, _ in lst)
        la.discard("0.0.0.0")
        la.discard("::")
        self.tcp, self.udp, self.local_addrs = tcp, udp, la

    def _label(self, pid: int):
        name, path = self.names.get(pid)
        if not name:
            return "PID %d" % pid, path
        svc = self.names.services.get(pid)
        return ("%s [%s] (%d)" % (name, svc, pid) if svc else "%s (%d)" % (name, pid)), path

    def lookup(self, d: Decoded):
        if d.l4 == "tcp":
            pid = self.tcp.get((d.src, d.sport, d.dst, d.dport))
            if pid is None:
                pid = self.tcp.get((d.dst, d.dport, d.src, d.sport))
            if pid is None or pid < 0:
                return "", ""
            label, path = self._label(pid)
            return label, "TCP connection table, exact 4-tuple match (snapshot). %s" % path
        if d.l4 == "udp":
            for lport, laddr in ((d.sport, d.src), (d.dport, d.dst)):
                pids = {pid for a, pid in self.udp.get(lport, []) if a in (laddr, "0.0.0.0", "::") and pid >= 0}
                if len(pids) == 1:
                    label, path = self._label(next(iter(pids)))
                    return label, "UDP local-port match only (lower confidence). %s" % path
        return "", ""


def _win_get_table(func, af: int, table_class: int):
    from ctypes import wintypes
    size = wintypes.DWORD(0)
    for _ in range(5):
        buf = ctypes.create_string_buffer(size.value) if size.value else None
        rc = func(buf, ctypes.byref(size), False, af, table_class, 0)
        if rc == 0:
            return buf.raw[:size.value]
        if rc != 122:  # ERROR_INSUFFICIENT_BUFFER
            return b""
    return b""


