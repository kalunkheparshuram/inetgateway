class IntelCache:
    """Local JSON cache of lookup results (indicator + VirusTotal counts + time) and the daily request counter."""
    TTL = {"ip": 86400, "domain": 86400, "file": 7 * 86400}
    MAX = 5000

    def __init__(self, path=None, clock=time.time, persist=True):
        self.path = path or os.path.join(config_dir(), "intel_cache.json")
        self.clock, self.persist = clock, persist
        self.entries, self.usage, self.warning = {}, {"date": "", "count": 0}, None
        self._lock = threading.RLock()

    @staticmethod
    def _valid(e) -> bool:
        try:
            return (isinstance(e, dict) and e["kind"] in ("ip", "domain", "file") and isinstance(e["q"], str)
                    and len(e["q"]) <= 300 and isinstance(e["t"], (int, float)) and e["status"] in ("ok", "notfound")
                    and all(isinstance(e[k], int) and not isinstance(e[k], bool) and 0 <= e[k] <= 10000
                            for k in ("mal", "sus", "har", "und"))
                    and isinstance(e.get("owner", ""), str) and isinstance(e.get("country", ""), str)
                    and (e.get("rep") is None or isinstance(e["rep"], int)))
        except (KeyError, TypeError):
            return False

    def load(self):
        if not self.persist:
            return
        try:
            with open(self.path, "r", encoding="utf-8") as f:
                raw = json.load(f)
        except FileNotFoundError:
            return
        except (OSError, ValueError):
            try:
                os.replace(self.path, self.path + ".bad")
            except OSError:
                pass
            self.warning = "Threat-intel cache was unreadable and was set aside (intel_cache.json.bad)."
            return
        if not isinstance(raw, dict):
            return
        u = raw.get("usage")
        if isinstance(u, dict) and isinstance(u.get("date"), str) and isinstance(u.get("count"), int) and u["count"] >= 0:
            self.usage = {"date": u["date"][:10], "count": min(u["count"], 10 ** 7)}
        ents = raw.get("entries")
        if isinstance(ents, dict):
            for k, e in list(ents.items())[:self.MAX]:
                if self._valid(e) and k == e["kind"] + ":" + e["q"]:
                    e.setdefault("rep", None)
                    e.setdefault("note", "")
                    self.entries[k] = {f: e.get(f) for f in RESULT_FIELDS}

    def _today(self) -> str:
        return time.strftime("%Y-%m-%d", time.localtime(self.clock()))

    def get(self, kind, value):
        with self._lock:
            e = self.entries.get(kind + ":" + value)
            if e and self.clock() - e["t"] < self.TTL[kind]:
                return dict(e)
        return None

    def peek(self, kind, value):
        with self._lock:
            e = self.entries.get(kind + ":" + value)
            return dict(e) if e else None

    def put(self, res):
        if res.get("status") not in ("ok", "notfound"):
            return
        with self._lock:
            if len(self.entries) >= self.MAX:
                for k in sorted(self.entries, key=lambda k: self.entries[k]["t"])[:self.MAX // 10]:
                    del self.entries[k]
            self.entries[res["kind"] + ":" + res["q"]] = {f: res.get(f) for f in RESULT_FIELDS}

    def used_today(self) -> int:
        with self._lock:
            return self.usage["count"] if self.usage["date"] == self._today() else 0

    def bump(self):
        with self._lock:
            today = self._today()
            if self.usage["date"] != today:
                self.usage = {"date": today, "count": 0}
            self.usage["count"] += 1

    def recent(self, n=500):
        with self._lock:
            return sorted((dict(e) for e in self.entries.values()), key=lambda e: e["t"], reverse=True)[:n]

    def save(self):
        if not self.persist:
            return True
        with self._lock:
            data = {"version": 1, "usage": dict(self.usage), "entries": dict(self.entries)}
        tmp = None
        try:
            os.makedirs(os.path.dirname(self.path), exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=os.path.dirname(self.path), suffix=".tmp")
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(data, f)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, self.path)
            return True
        except OSError:
            if tmp:
                try:
                    os.remove(tmp)
                except OSError:
                    pass
            return False

    def clear(self):
        with self._lock:
            self.entries.clear()
        self.save()


def _dpapi(data: bytes, protect: bool) -> bytes:
    """Windows DPAPI: encrypts for the current Windows user. Not testable off Windows."""
    from ctypes import wintypes

    class Blob(ctypes.Structure):
        _fields_ = [("cbData", wintypes.DWORD), ("pbData", ctypes.POINTER(ctypes.c_char))]
    crypt32 = ctypes.WinDLL("crypt32", use_last_error=True)
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    fn = crypt32.CryptProtectData if protect else crypt32.CryptUnprotectData
    fn.argtypes = [ctypes.POINTER(Blob), ctypes.c_void_p, ctypes.POINTER(Blob), ctypes.c_void_p,
                   ctypes.c_void_p, wintypes.DWORD, ctypes.POINTER(Blob)]
    fn.restype = wintypes.BOOL
    kernel32.LocalFree.argtypes = [ctypes.c_void_p]
    kernel32.LocalFree.restype = ctypes.c_void_p
    buf = ctypes.create_string_buffer(data, len(data))
    bin_ = Blob(len(data), ctypes.cast(buf, ctypes.POINTER(ctypes.c_char)))
    bout = Blob()
    if not fn(ctypes.byref(bin_), None, None, None, None, 1, ctypes.byref(bout)):  # 1 = CRYPTPROTECT_UI_FORBIDDEN
        raise OSError("Windows could not %s the key" % ("encrypt" if protect else "decrypt"))
    try:
        return ctypes.string_at(bout.pbData, bout.cbData)
    finally:
        kernel32.LocalFree(ctypes.cast(bout.pbData, ctypes.c_void_p))


class KeyStore:
    """Stores the API key in its own file, never in config.json. DPAPI-encrypted on Windows; elsewhere only base64
    (not encryption) with owner-only file permissions. The key is never logged, exported or shown."""

    def __init__(self, path=None):
        self.path = path or os.path.join(config_dir(), "vt_key.json")

    @property
    def scheme(self) -> str:
        return "dpapi" if os.name == "nt" else "plain"

    def exists(self) -> bool:
        return os.path.isfile(self.path)

    def save(self, key: str):
        if not valid_api_key(key):
            raise ValueError("That does not look like a VirusTotal API key (letters and digits only).")
        raw = key.encode("ascii")
        blob = _dpapi(raw, True) if self.scheme == "dpapi" else raw
        data = {"v": 1, "scheme": self.scheme, "data": base64.b64encode(blob).decode("ascii")}
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(self.path), suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(data, f)
                f.flush()
                os.fsync(f.fileno())
            if os.name != "nt":
                os.chmod(tmp, 0o600)
            os.replace(tmp, self.path)
        except OSError:
            try:
                os.remove(tmp)
            except OSError:
                pass
            raise

    def load(self):
        try:
            with open(self.path, "r", encoding="utf-8") as f:
                d = json.load(f)
            blob = base64.b64decode(d["data"], validate=True)
            if d.get("scheme") == "dpapi":
                if os.name != "nt":
                    return None
                blob = _dpapi(blob, False)
            key = blob.decode("ascii")
            return key if valid_api_key(key) else None
        except (OSError, ValueError, KeyError, TypeError):
            return None

    def clear(self):
        try:
            os.remove(self.path)
        except FileNotFoundError:
            pass


class IntelService:
    """Background lookups: one worker thread, bounded priority queue, rate limit, daily cap, cache, no redirects."""
    MAX_QUEUE = 200

    def __init__(self, cache, results, clock=time.time, wait=None, fetch=None, hash_fn=None):
        self.cache, self.results, self.clock, self.fetch = cache, results, clock, fetch
        self.hash_fn = hash_fn or sha256_file
        self.stop_evt = threading.Event()
        self._wait = wait or (lambda s: self.stop_evt.wait(s))
        self.jobs = queue.PriorityQueue()
        self._seq, self._pending, self._lock = 0, set(), threading.Lock()
        self.key, self.rpm, self.daily = None, 4, 500
        self.last_call = self.backoff_until = 0.0
        self.key_rejected = False
        self.interval_override = None  # demo/tests only
        self.status, self.thread, self._memo = "Off", None, {}

    def configure(self, key, rpm, daily):
        if key != self.key:
            self.key_rejected = False
        self.key, self.rpm, self.daily = key, max(1, min(60, int(rpm))), max(1, int(daily))

    def queue_size(self) -> int:
        return self.jobs.qsize()

    def submit(self, kind, value, ctx="", manual=False) -> str:
        if kind != "path":
            hit = self.cache.get(kind, value)
            if hit is not None:
                if manual:
                    self.results.put(dict(hit, ctx=ctx, cached=True))
                return "cached"
        key = (kind, value)
        with self._lock:
            if key in self._pending:
                return "duplicate"
            if not manual and self.jobs.qsize() >= self.MAX_QUEUE:
                return "full"
            self._pending.add(key)
            self._seq += 1
            self.jobs.put((0 if manual else 1, self._seq, kind, value, ctx, 0))
        return "queued"

    def start(self):
        if self.thread and self.thread.is_alive():
            return
        self.stop_evt.clear()
        self.thread = threading.Thread(target=self._run, daemon=True)
        self.thread.start()
        self.status = "Ready"

    def stop(self):
        self.stop_evt.set()
        self.status = "Off"

    def _run(self):
        while not self.stop_evt.is_set():
            try:
                item = self.jobs.get(timeout=0.5)
            except queue.Empty:
                continue
            try:
                self.process(item)
            except Exception as e:  # never let a bad job kill the worker
                self.status = "Error: %s" % type(e).__name__

    def _hash(self, path):
        try:
            st = os.stat(path)
            sig = (st.st_size, st.st_mtime)
        except OSError:
            sig = None
            if self.hash_fn is sha256_file:
                return None
        m = self._memo.get(path)
        if m and m[0] == sig:
            return m[1]
        sha = self.hash_fn(path)
        if sha:
            if len(self._memo) > 4096:
                self._memo.clear()
            self._memo[path] = (sig, sha)
        return sha

    def process(self, item):
        prio, seq, kind, value, ctx, attempts = item
        pkey, requeued = (kind, value), False
        try:
            if kind == "path":
                sha = self._hash(value)
                if not sha:
                    self.status = "Skipped an unreadable file"
                    return None
                kind, value, ctx = "file", sha, ctx or ntpath.basename(value)
            hit = self.cache.get(kind, value)
            if hit is not None:
                self.results.put(dict(hit, ctx=ctx))
                return hit
            if not self.key or self.key_rejected:
                self.status = "API key rejected by VirusTotal" if self.key_rejected else "No valid API key"
                return None
            if self.cache.used_today() >= self.daily:
                self.status = "Daily limit reached"
                stub = parse_vt_response(kind, value, -1, b"", self.clock())
                stub["status"] = "dailylimit"
                self.results.put(dict(stub, ctx=ctx))
                return stub
            now = self.clock()
            gap = 60.0 / self.rpm if self.interval_override is None else self.interval_override
            wait = max(0.0, self.last_call + gap - now, self.backoff_until - now)
            if wait > 0 and self._wait(wait):
                return None  # stopping
            res = parse_vt_response(kind, value, *(self.fetch or default_fetch)(vt_url(kind, value), self.key), self.clock())
            self.last_call = self.clock()
            self.cache.bump()
            if res["status"] == "ratelimited":
                self.backoff_until = self.clock() + 60.0
                if attempts < 2:
                    self.status = "Rate limited by VirusTotal; retrying in 60 s"
                    self.jobs.put((prio, seq, pkey[0], pkey[1], ctx, attempts + 1))
                    requeued = True
                    self.cache.save()
                    return res
            elif res["status"] == "badkey":
                self.key_rejected = True
                self.status = "API key rejected by VirusTotal"
            elif res["status"] in ("ok", "notfound"):
                self.cache.put(res)
                self.status = "OK"
            else:
                self.status = "Lookup failed: " + (res["note"] or "unknown error")
            self.cache.save()
            self.results.put(dict(res, ctx=ctx))
            return res
        finally:
            if not requeued:
                with self._lock:
                    self._pending.discard(pkey)


